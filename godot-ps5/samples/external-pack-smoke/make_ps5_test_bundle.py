#!/usr/bin/env python3
"""Package the independent Godot-4 external smoke PCK for a PS5 filesystem test.

No SDK, fake PCK, or native PS5 compilation: the input must be a real PCK
generated by Godot 4.7.2 and separately validated on the host runner.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import struct
import zipfile


def check_godot4_pack(path: Path) -> bytes:
    data = path.read_bytes()
    if len(data) < 64 or data[:4] != b"GDPC":
        raise ValueError("missing Godot GDPC PCK header")
    fmt, major, minor = struct.unpack_from("<III", data, 4)
    if not (2 <= fmt <= 4 and major == 4 and 0 <= minor <= 7):
        raise ValueError(f"incompatible PCK header: fmt={fmt} engine={major}.{minor}")
    return data


def build_bundle(pack: Path, destination: Path) -> tuple[Path, str]:
    data = check_godot4_pack(pack)
    destination.mkdir(parents=True, exist_ok=True)
    checksum = hashlib.sha256(data).hexdigest()
    target = destination / "GodotPS5-M8c-External-PCK-PS5-TEST.zip"
    instructions = (
        "GODOT PS5 M8c / EXTERNAL PCK HARDWARE ACCEPTANCE\n"
        "Runner: PPSA99847 v0.1.2 (already installed from TESTBUILD)\n"
        "\n"
        "Copy the CONTENTS of this GodotPS5/ folder into /data/GodotPS5/\n"
        "without changing the relative paths:\n"
        "  /data/GodotPS5/launch.txt\n"
        "  /data/GodotPS5/games/external-smoke.pck\n"
        "\n"
        "Launch PPSA99847. The first scene shows a magenta ring on blue;\n"
        "the second shows a cyan circle and a square. Press X to toggle\n"
        "colors. The test should exit itself after about 420 frames.\n"
        "\n"
        "For diagnostics copy all three files from /data/GodotPS5/:\n"
        "  gles3-runtime.log, gles3-stdout.log, gles3-stderr.log\n"
        "Verify PACK_SOURCE=CONFIG and GODOT_PS5_EXTERNAL_FINISHED.\n"
        "Delete launch.txt to restore the built-in Pong.\n"
        "\n"
        "Not a universal Godot launcher; PS5 hardware test still required.\n"
    )
    with zipfile.ZipFile(target, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=7) as z:
        z.writestr("GodotPS5/games/external-smoke.pck", data)
        z.writestr("GodotPS5/launch.txt", "external-smoke.pck\n")
        z.writestr("GodotPS5/README-M8c.txt", instructions)
        z.writestr("GodotPS5/external-smoke.sha256",
                   f"{checksum}  games/external-smoke.pck\n")
    with zipfile.ZipFile(target) as z:
        if z.testzip() is not None or z.read("GodotPS5/games/external-smoke.pck") != data:
            raise RuntimeError("test package ZIP integrity failed")
        if z.read("GodotPS5/launch.txt") != b"external-smoke.pck\n":
            raise RuntimeError("launch.txt mismatch")
    return target, checksum


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pack", type=Path)
    parser.add_argument("out", type=Path)
    args = parser.parse_args()
    target, digest = build_bundle(args.pack, args.out)
    print(f"GODOT_PS5_EXTERNAL_BUNDLE_READY {target}")
    print(f"GODOT_PS5_EXTERNAL_PCK_SHA256={digest}")


if __name__ == "__main__":
    main()
